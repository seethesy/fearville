// FEAR-173: find player-visible text that is not yet in the editable text
// registry (lib/ui-text/registry.ts). Read-only; prints a Markdown report.
//
//   node scripts/audit-ui-text.mjs > docs/content-review/ui-text-audit.md
//
// Heuristics (TypeScript AST, no type checking):
// - JSX text and string literals in JSX text attributes (aria-label, title,
//   placeholder, alt, label) in app/ and components/.
// - `Error('…')` / `throw Error('…')` messages in app/api and lib/ (shown to
//   players through API error responses).
// - String properties named title/body/summary/label/description/text/
//   message/name in lib/ data catalogs that are not yet registry-backed.
import ts from 'typescript';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

const ROOTS = ['app', 'components', 'lib', 'hooks'];
const SKIP =
  /(^|\/)(node_modules|ui|admin|staging|__tests__)\/|\.test\.|bank-data\.ts$|\.d\.ts$/;
// Catalogs already editable through the registry (FEAR-173 adapters).
const COVERED = [
  'lib/tutorials/content/',
  'lib/game/glossary.ts',
  'lib/game/types/roles.ts',
  'lib/game/role-tips',
];
const ATTRS = new Set(['aria-label', 'title', 'placeholder', 'alt', 'label']);
const PROPS = new Set([
  'title',
  'body',
  'summary',
  'label',
  'description',
  'text',
  'message',
  'hint',
]);
const visible = (s) => /[A-Za-z]{2,}/.test(s) && !/^[a-z][\w.-]*$/.test(s);

function files(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (SKIP.test(p + (statSync(p).isDirectory() ? '/' : ''))) continue;
    if (statSync(p).isDirectory()) out.push(...files(p));
    else if (/\.(tsx?|mjs)$/.test(name)) out.push(p);
  }
  return out;
}

const found = []; // { file, line, kind, text }
for (const file of ROOTS.flatMap(files)) {
  if (COVERED.some((c) => file.startsWith(c))) continue;
  const src = readFileSync(file, 'utf8');
  const sf = ts.createSourceFile(file, src, ts.ScriptTarget.Latest, true);
  const add = (node, kind, text) => {
    const clean = text.replace(/\s+/g, ' ').trim();
    if (!visible(clean)) return;
    const { line } = sf.getLineAndCharacterOfPosition(node.getStart());
    found.push({ file, line: line + 1, kind, text: clean });
  };
  const ui = file.startsWith('app/') || file.startsWith('components/');
  const visit = (node) => {
    if (ui && ts.isJsxText(node)) add(node, 'page copy', node.text);
    else if (
      ui &&
      ts.isJsxAttribute(node) &&
      ATTRS.has(node.name.getText()) &&
      node.initializer &&
      ts.isStringLiteral(node.initializer)
    )
      add(node, 'attribute', node.initializer.text);
    else if (
      (ts.isCallExpression(node) || ts.isNewExpression(node)) &&
      node.expression.getText() === 'Error' &&
      node.arguments &&
      node.arguments[0] &&
      (ts.isStringLiteral(node.arguments[0]) ||
        ts.isNoSubstitutionTemplateLiteral(node.arguments[0])) &&
      node.arguments[0].text !== 'FORBIDDEN'
    )
      add(node, 'error message', node.arguments[0].text);
    else if (
      !ui &&
      ts.isPropertyAssignment(node) &&
      PROPS.has(node.name.getText()) &&
      (ts.isStringLiteral(node.initializer) ||
        ts.isNoSubstitutionTemplateLiteral(node.initializer))
    )
      add(node, 'catalog text', node.initializer.text);
    ts.forEachChild(node, visit);
  };
  visit(sf);
}

const area = (f) => {
  if (f.startsWith('lib/rite/grid')) return 'Sphinx clue templates';
  if (f.startsWith('lib/rite') || f.startsWith('components/rite'))
    return 'Night Rite';
  if (/rules|glossary/.test(f)) return 'Rules and glossary';
  if (/tutorial/.test(f)) return 'Tutorials and help';
  if (/push|notif|mail/.test(f)) return 'Notifications and emails';
  if (f.startsWith('lib/game') || f.startsWith('app/table')) return 'Game table';
  if (/social|friends|profile|stats/.test(f)) return 'Social and profiles';
  if (/account|privacy|terms|delete/.test(f)) return 'Accounts and legal';
  return 'Other pages';
};
const byArea = new Map();
for (const f of found) {
  const a = area(f.file);
  if (!byArea.has(a)) byArea.set(a, []);
  byArea.get(a).push(f);
}
const kinds = [...new Set(found.map((f) => f.kind))];
const out = [];
out.push('# Editable text audit (FEAR-173)');
out.push('');
out.push(
  'Generated by `node scripts/audit-ui-text.mjs`. Lists player-visible text that is **not yet** in the editable text registry. Heuristic: expect a few false positives (developer-only strings) and misses (strings built from expressions).',
);
out.push('');
out.push('## Already editable');
out.push('');
out.push(
  '- Home, lobby, navigation and footer labels (FEAR-40)\n- Every tutorial: walkthroughs, section tutorials, Storyteller tour and sections, Night Rite guides (titles, summaries, steps)\n- Glossary terms, definitions and examples\n- Role names and ability text for every script (display only)\n- Role tips for every script',
);
out.push('');
out.push('## Not yet editable');
out.push('');
out.push('| Area | ' + kinds.join(' | ') + ' | Total |');
out.push('|---|' + kinds.map(() => '---:').join('|') + '|---:|');
for (const [a, list] of [...byArea].sort((x, y) => y[1].length - x[1].length))
  out.push(
    `| ${a} | ${kinds.map((k) => list.filter((f) => f.kind === k).length).join(' | ')} | ${list.length} |`,
  );
out.push(
  `| **All** | ${kinds.map((k) => found.filter((f) => f.kind === k).length).join(' | ')} | **${found.length}** |`,
);
out.push('');
for (const [a, list] of [...byArea].sort((x, y) => y[1].length - x[1].length)) {
  out.push(`### ${a} (${list.length})`);
  out.push('');
  const perFile = new Map();
  for (const f of list) perFile.set(f.file, [...(perFile.get(f.file) ?? []), f]);
  for (const [file, items] of [...perFile].sort(
    (x, y) => y[1].length - x[1].length,
  )) {
    out.push(`<details><summary><code>${file}</code> (${items.length})</summary>`);
    out.push('');
    for (const i of items)
      out.push(
        `- L${i.line} · ${i.kind}: ${i.text.length > 120 ? i.text.slice(0, 117) + '…' : i.text}`.replaceAll('|', '\\|'),
      );
    out.push('');
    out.push('</details>');
    out.push('');
  }
}
process.stdout.write(out.join('\n') + '\n');
