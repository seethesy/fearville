// Offline only: certify varied puzzles and their optimal paths. Live requests
// take suffixes of these paths, so difficulty changes never need a solver.
import { writeFileSync } from 'node:fs';
import { generateBoard, solveBoard } from '../lib/rite/board.ts';
import { generateLab, solveLab } from '../lib/rite/lab.ts';

const bank = { board: [], lab: [] };
for (const [maxRemovedBlocks, moves, count] of [
  [0, 32, 32],
  [1, 20, 16],
  [2, 14, 16],
  [3, 9, 16],
]) {
  for (let i = 0; i < count; i++) {
    const puzzle = generateBoard(`escape-v2-${maxRemovedBlocks}-${i}`, 3, {
      minMoves: moves,
      maxMoves: moves,
      maxRemovedBlocks,
    });
    const solution = solveBoard(puzzle.blocks, 200000);
    if (!solution || solution.length !== puzzle.par)
      throw Error('Escape certification failed.');
    bank.board.push({ puzzle, solution, maxRemovedBlocks });
  }
  console.log(
    `Certified ${count} Escape layouts (removal budget ${maxRemovedBlocks}).`,
  );
}
for (const [colors, moves] of [
  [4, 9],
  [7, 20],
  [10, 32],
]) {
  for (let i = 0; i < 24; i++) {
    const puzzle = generateLab(`laboratory-v2-${colors}-${i}`, 3, {
      minMoves: moves,
      maxMoves: moves,
      colors,
      emptyVials: 2,
    });
    const solution = solveLab(puzzle.vials, 200000);
    if (!solution || solution.length !== puzzle.par)
      throw Error('Laboratory certification failed.');
    bank.lab.push({ puzzle, solution, colors, emptyVials: 2 });
  }
  console.log(`Certified 24 Laboratory layouts (${colors} liquids).`);
}
writeFileSync(
  'lib/rite/bank-data.ts',
  "// GENERATED by scripts/generate-rite-bank.mjs — do not edit or read; see AGENTS.md. Never generate on live requests.\nimport type { PuzzleBank } from './bank-types.ts';\nexport const PUZZLE_BANK: PuzzleBank = " +
    JSON.stringify(bank) +
    ';\n',
);
