// Offline only: certify hard puzzles once, never while serving a player.
import { writeFileSync } from 'node:fs';
import { generateBoard } from '../lib/rite/board.ts';
import { generateLab } from '../lib/rite/lab.ts';
const bank = { board: [], lab: [] };
for (let i = 0; i < 16; i++) {
  bank.board.push(generateBoard(`certified-board-${i}`, 3));
  bank.lab.push(generateLab(`certified-lab-${i}`, 3));
  console.log(`Certified puzzle pair ${i + 1}/16`);
}
writeFileSync('lib/rite/bank-data.ts', '// Generated by scripts/generate-rite-bank.mjs. Do not generate on live requests.\nimport type { BoardState, LabState } from \'./types.ts\';\nexport const PUZZLE_BANK: { board: BoardState[]; lab: LabState[] } = ' + JSON.stringify(bank) + ';\n');
