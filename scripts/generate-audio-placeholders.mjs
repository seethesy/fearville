// Original, freely reusable placeholders; no third-party assets.
import { mkdirSync, writeFileSync } from 'node:fs';
mkdirSync('public/audio',{recursive:true});
function wav(name,frequency=0) {
  const rate=22050, seconds=frequency ? .3 : 1, samples=Math.floor(rate*seconds);
  const comment=Buffer.from('GENERATED by scripts/generate-audio-placeholders.mjs; do not hand-edit.\0');
  const padded=comment.length+(comment.length%2), infoLength=12+padded;
  const dataOffset=36+8+infoLength;
  const buffer=Buffer.alloc(dataOffset+8+samples*2);
  buffer.write('RIFF'); buffer.writeUInt32LE(buffer.length-8,4); buffer.write('WAVEfmt ',8);
  buffer.writeUInt32LE(16,16); buffer.writeUInt16LE(1,20); buffer.writeUInt16LE(1,22);
  buffer.writeUInt32LE(rate,24); buffer.writeUInt32LE(rate*2,28); buffer.writeUInt16LE(2,32); buffer.writeUInt16LE(16,34);
  buffer.write('LIST',36); buffer.writeUInt32LE(infoLength,40); buffer.write('INFOICMT',44);
  buffer.writeUInt32LE(comment.length,52); comment.copy(buffer,56);
  buffer.write('data',dataOffset); buffer.writeUInt32LE(samples*2,dataOffset+4);
  let phase=0;
  for(let i=0;i<samples;i++) {
    const t=i/rate;
    phase+=2*Math.PI*frequency*Math.pow(.5,t/.18)/rate;
    const envelope=frequency ? .12*Math.pow(.0001/.12,t/.25) : 0;
    buffer.writeInt16LE(Math.round(Math.sin(phase)*envelope*32767),dataOffset+8+i*2);
  }
  writeFileSync(`public/audio/${name}.wav`,buffer);
}
wav('placeholder'); wav('phase',660); wav('error',180);
console.log('Generated silent music and original phase/error PCM placeholders.');
