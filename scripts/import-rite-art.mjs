// Import the approved painted art; no image generation or game data is involved.
// node scripts/import-rite-art.mjs --sprites <sprite-pack> --surfaces <surface-pack>
// Supply Sharp outside app dependencies with FEARVILLE_SHARP_MODULE if needed.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';

const args = process.argv.slice(2);
const option = (name) => args[args.indexOf(name) + 1];
if (!args.includes('--sprites') || !args.includes('--surfaces'))
  throw Error(
    'Pass --sprites <approved sprite pack> --surfaces <approved surface pack>.',
  );
const spriteRoot = path.resolve(option('--sprites'));
const surfaceRoot = path.resolve(option('--surfaces'));
const require = createRequire(import.meta.url);
const sharp = require(process.env.FEARVILLE_SHARP_MODULE || 'sharp');
const destination = path.resolve('public/rite');
const sprites = JSON.parse(
  await readFile(path.join(spriteRoot, 'manifest.json'), 'utf8'),
);
const surfaces = JSON.parse(
  await readFile(path.join(surfaceRoot, 'manifest.json'), 'utf8'),
);
const imported = [];
async function exportImage(source, relative, width, height, lossless = true) {
  const original = await readFile(source);
  const target = path.join(destination, relative);
  await mkdir(path.dirname(target), { recursive: true });
  await sharp(original)
    .resize(width, height)
    .webp({ lossless, quality: 88, effort: 6 })
    .toFile(target);
  const data = await readFile(target);
  imported.push({
    file: '/rite/' + relative,
    width,
    height,
    bytes: data.length,
    sourceSha256: createHash('sha256').update(original).digest('hex'),
  });
  return '/rite/' + relative;
}
const spriteMap = {};
for (const asset of sprites.assets) {
  const variants = [];
  for (const scale of [1, 2]) {
    const name = 'sprites/' + asset.name + (scale === 2 ? '@2x' : '') + '.webp';
    variants.push(
      await exportImage(
        path.join(spriteRoot, asset.variants[scale]),
        name,
        asset.width * scale,
        asset.height * scale,
      ),
    );
  }
  spriteMap[asset.name] = {
    src: variants[0],
    src2x: variants[1],
    srcSet: variants[0] + ' 1x, ' + variants[1] + ' 2x',
    width: asset.width,
    height: asset.height,
  };
}
const surfaceMap = {};
for (const id of [
  'escape/board-6x6',
  'escape/board-7x7',
  'escape/board-8x8',
  'sphinx/street',
  'divination/omens-tablet',
  'grimoire/closed-cover',
]) {
  const asset = surfaces.assets.find((a) => a.id === id);
  const variants = [];
  for (const scale of [1, 2])
    variants.push(
      await exportImage(
        path.join(surfaceRoot, asset.files[scale + 'x'].png),
        'surfaces/' + id + (scale === 2 ? '@2x' : '') + '.webp',
        asset.logicalSize.width * scale,
        asset.logicalSize.height * scale,
      ),
    );
  surfaceMap[id] = {
    src: variants[0],
    src2x: variants[1],
    srcSet: variants[0] + ' 1x, ' + variants[1] + ' 2x',
    ...asset.logicalSize,
  };
}
for (const [name, source] of Object.entries({
  'grimoire-page': 'masters/parts/single-page.png',
  'grimoire-spread': 'masters/clean/grimoire-tall-spread.png',
  'grimoire-spread-short': 'masters/parts/open-book.png',
  'character-tray': 'masters/parts/character-tray.png',
  'activity-tray': 'masters/parts/activity-tray.png',
})) {
  const input = path.join(surfaceRoot, source);
  const { width, height } = await sharp(input).metadata();
  const src = await exportImage(
    input,
    'frames/' + name + '.webp',
    width,
    height,
  );
  surfaceMap[name] = { src, width, height };
}
const sceneMap = {};
for (const [key, scene] of Object.entries(surfaces.scenes)) {
  const { width, height } = scene.nativeSize;
  // Fit within the native painting, with no synthetic resolution increase.
  const w = key.endsWith('portrait') ? 900 : 1600,
    h = key.endsWith('portrait') ? 1600 : 900;
  const src = await exportImage(
    path.join(surfaceRoot, scene.master),
    'scenes/' + key + '.webp',
    Math.min(w, width),
    Math.min(h, height),
    false,
  );
  sceneMap[key] = src;
}
const data = {
  sprites: spriteMap,
  surfaces: surfaceMap,
  scenes: sceneMap,
  vialPaths: sprites.vials.shapes.map((shape) => shape.path),
  vialBottoms: surfaces.laboratory.visibleVialBottoms,
  lab: {
    portrait: surfaces.laboratory.portrait,
    landscape: surfaces.laboratory.landscape,
  },
  boards: surfaces.escape.boards.map(({ n, canvas, play, exit, withGrid }) => ({
    n,
    canvas,
    play,
    exit,
    asset: withGrid,
  })),
};
await writeFile(
  'lib/rite/art-assets.ts',
  '// GENERATED by scripts/import-rite-art.mjs from the approved Fearville artwork.\nexport const RITE_ART = ' +
    JSON.stringify(data, null, 2) +
    ' as const;\n',
);
await writeFile(
  path.join(destination, 'manifest.json'),
  JSON.stringify(
    {
      _generated: 'GENERATED by scripts/import-rite-art.mjs',
      sources: { sprites: sprites.created, surfaces: surfaces.created },
      files: imported,
    },
    null,
    2,
  ) + '\n',
);
await writeFile(
  path.join(destination, 'NOTICE.txt'),
  'GENERATED asset export from the user-approved Fearville artwork.\nPainted with built-in image generation, October 2026. Runtime images are optimized WebP exports; labels, rules, puzzle states and grid geometry remain separate.\nRegenerate with scripts/import-rite-art.mjs and the approved source packs.\n',
);
console.log(
  'Imported ' +
    imported.length +
    ' images (' +
    (imported.reduce((n, f) => n + f.bytes, 0) / 1024 / 1024).toFixed(1) +
    ' MiB).',
);
